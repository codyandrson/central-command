"""A session written by pydantic-ai 2.18 loads, renders and resumes at 2.66.

The fixture `tests/fixtures/pai_2_18_paused_session.json` is a real
`run_state` dumped by pydantic-ai 2.18.0 (the shape `durable.dump_run_state`
writes): a charter system prompt, a deferred skill loaded through
`load_capability` (2.18 also recorded an auto-load `search_tools` exchange),
the skill's tool called, an output-validator retry (a `retry-prompt` with no
tool), a `propose_action` that a `ModelRetry` carrying the ROUTE CHECK mark
handed back (a `retry-prompt` answering the call), and the redraft paused on
`CallDeferred` — the proposal awaiting the operator. It was generated by
`tests/fixtures/gen_pai_2_18_paused_session.py` under a pydantic-ai 2.18.0
interpreter (a `FunctionModel` run); regenerate it that way, never by hand.

Sessions parked before the upgrade live in the database in this shape and are
resumed after it, so: they must load (pydantic-ai 2.60 turns `retry-prompt`
into `ToolReturnPart(outcome='retried')` and `RetryFeedbackPart` on load),
every reader must still see the retries in BOTH the stored dict shape and the
loaded one, the resume must send the ORIGINAL persisted charter (the
`system_prompt=` rule), and the loaded skill's tool must still be there.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

from pydantic_ai import Agent, DeferredToolRequests, Tool
from pydantic_ai.capabilities import Capability
from pydantic_ai.messages import (
    ModelMessagesTypeAdapter,
    ModelRequest,
    ModelResponse,
    RetryFeedbackPart,
    SystemPromptPart,
    TextPart,
    ToolReturnPart,
)
from pydantic_ai.models.function import AgentInfo, FunctionModel

from central_command.api import nerve_gateway
from central_command.runtime import context, durable, session_recall, tools

FIXTURE = Path(__file__).parent / "fixtures" / "pai_2_18_paused_session.json"
CHARTER = "ORIGINAL CHARTER (2.18): you triage mail for the operator."
GUIDANCE = "SKILL: Jira guide. Always quote the issue key."


def _old() -> dict:
    return json.loads(FIXTURE.read_text())


def _rewritten() -> dict:
    """The same session as 2.66 writes it back after a load (what a resumed
    session's run_state holds from then on)."""
    rs = _old()
    rs["messages"] = ModelMessagesTypeAdapter.dump_python(durable.load_messages(rs), mode="json")
    return rs


def test_the_fixture_is_the_old_shape():
    kinds = [p["part_kind"] for m in _old()["messages"] for p in m["parts"]]
    assert kinds.count("retry-prompt") == 2, "the fixture must keep the 2.18 retry shape"
    assert "instruction-baseline" not in kinds and "instruction-delta" not in kinds


def test_an_old_history_loads_with_its_retries_in_the_new_shapes():
    msgs = durable.load_messages(_old())
    parts = [p for m in msgs for p in m.parts]
    feedback = [p for p in parts if isinstance(p, RetryFeedbackPart)]
    retried = [p for p in parts if isinstance(p, ToolReturnPart) and p.outcome == "retried"]
    assert len(feedback) == 1 and "Finish by proposing" in feedback[0].content
    assert len(retried) == 1 and retried[0].tool_name == "propose_action"
    assert retried[0].content.startswith(tools._ROUTE_CHECK_MARK)
    # The paused call is the one thing unanswered: the retried draft counts as answered.
    assert [c.tool_name for c in durable.unanswered_calls(msgs)] == ["propose_action"]
    assert durable.unanswered_calls(msgs)[0].tool_call_id == _old()["tool_call_id"]
    proposal = durable.proposal_from_call(durable.unanswered_calls(msgs)[0])
    assert proposal.actions[0].capability == "graph.add_episode"


def test_retry_text_reads_all_three_shapes():
    old = [p for m in _old()["messages"] for p in m["parts"] if p["part_kind"] == "retry-prompt"]
    assert all(durable.retry_text(p) for p in old)
    new = [p for m in _rewritten()["messages"] for p in m["parts"]]
    assert sorted(p["part_kind"] for p in new if durable.retry_text(p) is not None) == [
        "retry-feedback",
        "tool-return",
    ]
    objs = [p for m in durable.load_messages(_old()) for p in m.parts]
    assert sum(durable.retry_text(p) is not None for p in objs) == 2
    # An ordinary tool return is not a retry, in either form.
    plain = next(
        p for p in objs if isinstance(p, ToolReturnPart) and p.tool_name == "skill_jira_guide"
    )
    assert durable.retry_text(plain) is None
    assert durable.retry_text({"part_kind": "tool-return", "content": "x"}) is None


def test_every_reader_renders_the_retries_old_and_new():
    for rs in (_old(), _rewritten()):
        simple = durable.simplify_messages(rs)
        retries = [t for t in simple if t["kind"] == "retry-prompt"]
        assert any(
            t["content"].startswith(tools._ROUTE_CHECK_MARK) and t["tool"] == "propose_action"
            for t in retries
        )
        assert any("Finish by proposing" in t["content"] for t in retries)
        assert not any(
            t["kind"] == "tool-return" and tools._ROUTE_CHECK_MARK in t["content"] for t in simple
        ), "a retry is never read as a tool's result"

        chat = nerve_gateway._transcript_to_chat_messages(rs)
        results = [c for c in chat if c["role"] == "toolResult"]
        assert any(
            r["content"].startswith(tools._ROUTE_CHECK_MARK) and r["toolName"] == "propose_action"
            for r in results
        )
        assert any("Finish by proposing" in r["content"] for r in results)
        assert chat[0] == {"role": "system", "content": CHARTER, "timestamp": chat[0]["timestamp"]}

        rows = session_recall.extract(rs).parts
        refused = [r for r in rows if r[4].startswith("[the call was refused or malformed]")]
        assert any(tools._ROUTE_CHECK_MARK in r[4] for r in refused)
        assert any("Finish by proposing" in r[4] for r in refused)

    summary = context.render_for_summary(durable.load_messages(_old()))
    assert f"retry: {tools._ROUTE_CHECK_MARK}" in summary
    assert "retry: Finish by proposing" in summary


def test_the_route_check_is_not_asked_again_after_an_old_history_resumes():
    msgs = durable.load_messages(_old())
    proposal = durable.proposal_from_call(durable.unanswered_calls(msgs)[0])
    from types import SimpleNamespace

    ctx = SimpleNamespace(messages=msgs, deps=SimpleNamespace(session_id="s", agent_id="a"))
    assert tools._route_check(ctx, proposal) is None
    ctx.messages = msgs[:1]
    assert tools._route_check(ctx, proposal) is not None, (
        "the same draft is asked about in a fresh record"
    )


async def test_an_old_paused_session_resumes_under_its_original_charter(monkeypatch):
    """The resume goes through `durable.resume` (DeferredToolResults for the
    decided call). The agent it resumes under has a DIFFERENT charter now:
    the model must be sent the one persisted with the session, and the skill
    the session loaded must still be loaded."""
    monkeypatch.setattr(context, "_density", {})  # the wrapper calibrates; keep it here
    rs = _old()
    msgs = durable.load_messages(rs)
    seen = []

    def model(messages, info: AgentInfo):
        seen.append((messages, [t.name for t in info.function_tools]))
        return ModelResponse(parts=[TextPart("Recorded; nothing else to do.")])

    cap = Capability(
        id="jira-guide",
        description="How this Jira is used",
        instructions=GUIDANCE,
        defer_loading=True,
    )

    def skill_jira_guide(query: str) -> str:
        """Search the Jira guide."""
        return "guide"

    cap.tool_plain(name="skill_jira_guide")(skill_jira_guide)
    agent = Agent(
        context.WindowedModel(FunctionModel(model, model_name="cc-default")),
        system_prompt="NEW CHARTER: must never reach a resumed session.",
        output_type=[str, DeferredToolRequests],
        capabilities=[cap, *context.capabilities()],
        tools=[Tool(tools.propose_action, max_retries=10)],
    )
    result = await durable.resume(
        agent,
        msgs,
        rs["tool_call_id"],
        "approved: executed",
        agent_id="inbox-triage",
        session_id=None,
    )
    assert result.output == "Recorded; nothing else to do."
    wire, offered = seen[-1]
    system = [
        p.content
        for m in wire
        if isinstance(m, ModelRequest)
        for p in m.parts
        if isinstance(p, SystemPromptPart)
    ]
    assert CHARTER in system
    assert not any("NEW CHARTER" in s for s in system)
    assert not any(
        "NEW CHARTER" in (m.instructions or "") for m in wire if isinstance(m, ModelRequest)
    )
    assert "skill_jira_guide" in offered, "the skill loaded before the upgrade is still loaded"
    assert any(GUIDANCE in str(getattr(p, "content", "")) for m in wire for p in m.parts), (
        "the loaded skill's guidance (carried in the 2.18 load return) still reaches the model"
    )
    returns = [
        p
        for m in wire
        if isinstance(m, ModelRequest)
        for p in m.parts
        if isinstance(p, ToolReturnPart) and p.tool_call_id == rs["tool_call_id"]
    ]
    assert returns and returns[0].content == "approved: executed"
    # The resumed record is the old one plus the new turn, written in 2.66's shapes.
    record = result.all_messages()
    assert record[0].parts[0].content == CHARTER
    dumped = ModelMessagesTypeAdapter.dump_python(record, mode="json")
    assert ModelMessagesTypeAdapter.validate_python(copy.deepcopy(dumped))


async def test_a_session_paused_at_2_66_resumes_under_the_charter_it_was_paused_under():
    """The same rule for a session written after the upgrade: `system_prompt=`
    is persisted with the record, so a resume after a charter edit still sends
    the charter the proposal was drafted under (AGENTS.md, never
    `instructions=` for the charter)."""
    from pydantic_ai.messages import ToolCallPart

    from tests.test_route_check import _JIRA, _proposal

    seen = []

    def model(messages, info: AgentInfo):
        seen.append(messages)
        if len(seen) == 1:
            return ModelResponse(
                parts=[
                    ToolCallPart(
                        "propose_action",
                        {"proposal": _proposal(_JIRA).model_dump(mode="json")},
                        tool_call_id="call-p",
                    )
                ]
            )
        return ModelResponse(parts=[TextPart("done")])

    def build(charter):
        return Agent(
            FunctionModel(model),
            system_prompt=charter,
            output_type=[str, DeferredToolRequests],
            tools=[Tool(tools.propose_action, max_retries=10)],
        )

    from types import SimpleNamespace

    first = await build("CHARTER v1").run(
        "mail", deps=SimpleNamespace(session_id="sess_charter", agent_id="inbox-triage")
    )
    call = durable.extract_deferred(first)
    assert call is not None
    state = durable.dump_run_state(first, call.tool_call_id)
    msgs = durable.load_messages(json.loads(json.dumps(state)))
    result = await durable.resume(
        build("CHARTER v2"), msgs, call.tool_call_id, "approved", agent_id="inbox-triage"
    )
    assert result.output == "done"
    sent = [
        p.content
        for m in seen[-1]
        if isinstance(m, ModelRequest)
        for p in m.parts
        if isinstance(p, SystemPromptPart)
    ]
    assert sent == ["CHARTER v1"]
    assert not any(
        "CHARTER v2" in (m.instructions or "") for m in seen[-1] if isinstance(m, ModelRequest)
    )


