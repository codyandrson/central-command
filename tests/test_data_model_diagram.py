"""`docs/diagrams/data-model.md` must match `central_command/db/schema.sql`.

The page is generated by `scripts/gen_data_model_diagram.py` and is never
edited by hand. A diagram in the repository that has drifted from the schema
misleads quietly, so this test runs the generator's own `--check`: it fails
when the page on disk is not what the script would write, and when schema.sql
has a table the script's area and purpose lists do not know (or the lists name
a table that is gone). The fix is in the failure message: run the script, and
give a new table its area and one-line purpose first.
"""

from __future__ import annotations

import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "gen_data_model_diagram.py"


def test_the_data_model_page_matches_the_schema():
    result = subprocess.run(
        [sys.executable, str(SCRIPT), "--check"],
        cwd=ROOT, capture_output=True, text=True, timeout=60,
    )
    assert result.returncode == 0, (
        "docs/diagrams/data-model.md is stale or schema.sql has a table the "
        "generator does not know:\n" + result.stdout + result.stderr
    )
